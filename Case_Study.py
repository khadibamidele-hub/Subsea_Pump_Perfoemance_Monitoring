import numpy as np
import pandas as pd

# Create fake data (simulating 10 days of pump data, every 10 minutes)
np.random.seed(42)
time = pd.date_range(start='2026-01-01', periods=1440, freq='10min')

# Flow_m3h is the volumetric flow rate (m3 per hour) through the meter,
# NOT a total volume — it's a rate, measured fresh at every timestamp.
flow = np.random.normal(100, 5, 1440)  # Flow around 100 m3/h
pressure = 50 + (flow * 0.5) + np.random.normal(0, 2, 1440)  # Pressure depends on flow
temperature = 40 + (flow * 0.15) + np.random.normal(0, 1, 1440)  # Temperature depends on flow

# Inject a GRADUAL fault (realistic degradation, not a sudden cliff-edge drop)
fault_start, fault_end = 600, 800
pressure[fault_start:fault_end] += np.linspace(0, -15, fault_end - fault_start)
temperature[fault_start:fault_end] += np.linspace(0, 4, fault_end - fault_start)  # temp creeps up as pressure drops

# PVT effect: as pressure drops, the fluid expands, increasing the volumetric flow rate (m3/h) through the meter.
flow[fault_start:fault_end] += np.linspace(0, 3, fault_end - fault_start)

data = pd.DataFrame({
    'Timestamp': time,
    'Flow_m3h': flow,
    'Pressure_bar': pressure,
    'Temperature_C': temperature
})
data.to_csv('pump_data.csv', index=False)
print("Synthetic subsea pump data created with realistic PVT-coupled degradation (Pressure drops, Flow drifts up, Temperature rises).")

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt


class SubseaMonitor:
    """Condition-monitoring pipeline for simulated subsea pump sensor data.

    Loads pressure/flow/temperature readings, detects performance
    anomalies, computes a combined health score, generates a root-cause
    hypothesis report, and builds a 4-panel monitoring dashboard.

    Engineering thresholds used throughout (rolling window, Z-score cutoff,
    root-cause deltas) are simplified, illustrative values chosen to make
    the demo behave sensibly on synthetic data — not values calibrated
    against real OneSubsea equipment. In a production setting these would
    be tuned against historical failure data and equipment specifications.
    """

    def __init__(self, rolling_window=50, anomaly_z=2.5, health_alert_threshold=2.0):
        """Initializes the monitor with its detection thresholds.

        Args:
            rolling_window: Number of readings used to define the local
                "normal" baseline for anomaly detection. Data is sampled
                every 10 minutes, so 50 readings is roughly 8 hours —
                long enough to smooth out sensor noise, short enough to
                still react within a single operating shift.
            anomaly_z: Number of rolling standard deviations a pressure
                reading must deviate from its rolling mean to be flagged
                as a performance deviation. 2.5 is a common statistical
                convention balancing false alarms against missed events.
            health_alert_threshold: Composite health score above which the
                system is flagged with a System_Alert. A value of 2.0
                means Pressure/Flow/Temperature are, on average, 2
                standard deviations from their normal operating range.
        """
        self.rolling_window = rolling_window
        self.anomaly_z = anomaly_z
        self.health_alert_threshold = health_alert_threshold
        self.df = None
        self.events = None

    def load_data(self, filepath):
        """Loads sensor data from CSV and parses the timestamp column.

        Args:
            filepath: Path to the CSV produced by create_data.py, containing
                Timestamp, Flow_m3h, Pressure_bar and Temperature_C columns.

        Returns:
            self, so calls can be chained.
        """
        self.df = pd.read_csv(filepath)
        self.df['Timestamp'] = pd.to_datetime(self.df['Timestamp'])
        return self

    def detect_anomalies(self):
        """Flags pressure readings that deviate from their rolling baseline.

        A rolling mean/std (window = self.rolling_window) is used instead
        of one fixed mean/std for the whole series, because pump operating
        conditions drift slowly over time — a rolling baseline adapts to
        that drift instead of flagging normal variation as anomalous. Also
        computes a rolling rate-of-change on pressure to catch a sustained
        downward trend before it fully deviates (an early-warning signal,
        not just a post-hoc flag).

        Returns:
            self.
        """
        df = self.df
        rolling_mean = df['Pressure_bar'].rolling(self.rolling_window).mean()
        rolling_std = df['Pressure_bar'].rolling(self.rolling_window).std()
        df['Anomaly'] = abs(df['Pressure_bar'] - rolling_mean) > (self.anomaly_z * rolling_std)
        df['Anomaly'] = df['Anomaly'].fillna(False)

        df['Pressure_RateOfChange'] = df['Pressure_bar'].diff().rolling(20).mean()
        df['EarlyWarning'] = df['Pressure_RateOfChange'] < -0.15
        return self

    def calculate_health_index(self):
        """Combines Pressure, Flow and Temperature into one health score.

        Each variable is converted to a Z-score (how many standard
        deviations it sits from its own overall mean), then the three
        Z-scores are averaged into a single Composite_Health value. One
        combined number is more useful for a status report than three
        separate raw sensor charts, since it reflects overall equipment
        state at a glance. Composite_Health above
        self.health_alert_threshold is flagged as a System_Alert.

        Returns:
            self.
        """
        df = self.df
        z_pressure = (df['Pressure_bar'] - df['Pressure_bar'].mean()) / df['Pressure_bar'].std()
        z_flow = (df['Flow_m3h'] - df['Flow_m3h'].mean()) / df['Flow_m3h'].std()
        z_temp = (df['Temperature_C'] - df['Temperature_C'].mean()) / df['Temperature_C'].std()

        df['Composite_Health'] = (z_pressure.abs() + z_flow.abs() + z_temp.abs()) / 3
        df['System_Alert'] = df['Composite_Health'] > self.health_alert_threshold
        return self

    def _hypothesize_root_cause(self, pressure_drop, temp_rise, flow_erratic):
        """Applies a simple rule-of-thumb to suggest a likely failure mode.

        This is a simplified heuristic for demonstration, not a validated
        diagnostic model — it distinguishes three plausible subsea pump
        failure signatures by which combination of Pressure, Temperature
        and Flow behaviour they typically show.

        Args:
            pressure_drop: True if mean pressure during the event dropped
                meaningfully below the overall baseline.
            temp_rise: True if mean temperature during the event rose
                meaningfully above the overall baseline.
            flow_erratic: True if flow variability during the event was
                notably higher than its baseline variability.

        Returns:
            A short text hypothesis for the likely root cause.
        """
        if pressure_drop and temp_rise:
            return "Suspected Impeller Wear / Recirculation"
        elif pressure_drop and not temp_rise:
            return "Suspected Suction Valve Throttling or Leak"
        elif flow_erratic and not pressure_drop:
            return "Suspected Multiphase Flow Meter Error or Slugging"
        else:
            return "Undetermined - Review Manually"

    def generate_rca_report(self):
        """Groups anomaly readings into events and hypothesizes a cause for each.

        Consecutive anomalous readings are grouped into single "events"
        rather than reported individually, because an engineer reviewing a
        monthly report cares about how many distinct degradation episodes
        occurred and how severe each was — not a raw list of hundreds of
        flagged timestamps. Each event's average Pressure/Flow/Temperature
        is compared against the dataset's overall baseline to hypothesize
        a likely root cause.

        Returns:
            self. Also writes rca_report.csv to disk.
        """
        df = self.df
        baseline_pressure = df['Pressure_bar'].mean()
        baseline_temp = df['Temperature_C'].mean()
        baseline_flow_std = df['Flow_m3h'].std()

        df['Event_Group'] = (df['Anomaly'] != df['Anomaly'].shift()).cumsum()
        anomaly_rows = df[df['Anomaly']]

        records = []
        for _, group in anomaly_rows.groupby('Event_Group'):
            pressure_drop = (baseline_pressure - group['Pressure_bar'].mean()) > 3
            temp_rise = (group['Temperature_C'].mean() - baseline_temp) > 1
            flow_erratic = group['Flow_m3h'].std() > (baseline_flow_std * 1.5)

            records.append({
                'Start': group['Timestamp'].iloc[0],
                'End': group['Timestamp'].iloc[-1],
                'Duration_readings': len(group),
                'Max_Deviation_bar': round(group['Pressure_bar'].min() - baseline_pressure, 2),
                'Root_Cause_Hypothesis': self._hypothesize_root_cause(pressure_drop, temp_rise, flow_erratic),
            })

        self.events = pd.DataFrame(records)
        self.events.to_csv('rca_report.csv', index=False)
        return self

    def create_dashboard(self, filename='pump_dashboard.png'):
        """Builds and saves a 4-panel monitoring dashboard.

        Panel 1 shades each detected event's real time span directly from
        the events table (rather than a hardcoded date range), so the
        chart stays correct even if the anomaly-detection parameters
        change. Panel 4 (Composite Health) gives an at-a-glance view
        matching the alert threshold used in calculate_health_index().

        Args:
            filename: Output path for the saved dashboard image.

        Returns:
            self.
        """
        df = self.df
        fig, (ax1, ax2, ax3, ax4) = plt.subplots(4, 1, figsize=(12, 14))

        # Plot 1: Pressure over time, with dynamically detected degradation zones
        ax1.plot(df['Timestamp'], df['Pressure_bar'], 'b-', linewidth=0.8, label='Pressure')
        for i, row in self.events.iterrows():
            ax1.axvspan(row['Start'], row['End'], alpha=0.2, color='orange',
                        label='Degradation Zone' if i == 0 else None)
        ax1.scatter(df[df['Anomaly']]['Timestamp'], df[df['Anomaly']]['Pressure_bar'],
                    color='red', s=25, label='Performance Deviation')
        ax1.set_ylabel('Pressure (bar)')
        ax1.set_title('Subsea Pump — Real-Time Pressure Monitoring (Rolling Anomaly)')
        ax1.legend()
        ax1.grid(True, alpha=0.3)

        # Plot 2: Rate of change — early degradation signal
        ax2.plot(df['Timestamp'], df['Pressure_RateOfChange'], 'g-', linewidth=0.9, label='Rate of Change')
        ax2.axhline(0, color='grey', linewidth=0.6)
        ax2.scatter(df[df['EarlyWarning']]['Timestamp'], df[df['EarlyWarning']]['Pressure_RateOfChange'],
                    color='orange', s=15, label='Early Warning')
        ax2.set_ylabel('bar / reading')
        ax2.set_title('Pressure Rate of Change (Early Degradation Signal)')
        ax2.legend()
        ax2.grid(True, alpha=0.3)

        # Plot 3: Flow-Pressure-Temperature (PVT view)
        sc = ax3.scatter(df['Flow_m3h'], df['Pressure_bar'], c=df['Temperature_C'],
                          cmap='coolwarm', alpha=0.6, s=20)
        plt.colorbar(sc, ax=ax3, label='Temperature (\u00b0C)')
        ax3.set_xlabel('Flow (m\u00b3/h)')
        ax3.set_ylabel('Pressure (bar)')
        ax3.set_title('Flow\u2013Pressure\u2013Temperature Relationship (PVT View)')
        ax3.grid(True, alpha=0.3)

        # Plot 4: Composite Health Index
        ax4.plot(df['Timestamp'], df['Composite_Health'], color='purple', linewidth=0.9, label='Composite Health')
        ax4.axhline(self.health_alert_threshold, color='red', linestyle='--', linewidth=1,
                    label=f'Alert Threshold ({self.health_alert_threshold})')
        ax4.set_ylabel('Composite Health Score')
        ax4.set_xlabel('Timestamp')
        ax4.set_title('Composite Health Index (Pressure + Flow + Temperature)')
        ax4.legend()
        ax4.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig(filename, dpi=150)
        plt.show()
        return self

    def run_pipeline(self, filepath='pump_data.csv'):
        """Runs the full pipeline in order: load, analyze, report, visualize.

        Args:
            filepath: Path to the input CSV produced by create_data.py.

        Returns:
            self, with self.df and self.events populated.
        """
        (self.load_data(filepath)
             .detect_anomalies()
             .calculate_health_index()
             .generate_rca_report()
             .create_dashboard())
        print(f"Pipeline complete. {len(self.events)} events detected — see rca_report.csv")
        print(self.events)
        return self


