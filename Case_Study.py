def load_data(filepath='pump_data.csv', rolling_window=50, anomaly_z=2.5):
    """Loads sensor data and re-runs the same anomaly flagging used in analyze_data.py.

    Kept standalone (no import from analyze_data.py) so this script can be
    run and understood on its own. The rolling window and threshold match
    analyze_data.py's detect_anomalies() so both scripts agree on what
    counts as anomalous.

    Args:
        filepath: Path to the CSV produced by create_data.py.
        rolling_window: Rolling baseline window, in readings.
        anomaly_z: Anomaly threshold, in rolling standard deviations.

    Returns:
        The sensor DataFrame with an added boolean 'Anomaly' column.
    """
    df = pd.read_csv(filepath)
    df['Timestamp'] = pd.to_datetime(df['Timestamp'])

    rolling_mean = df['Pressure_bar'].rolling(rolling_window).mean()
    rolling_std = df['Pressure_bar'].rolling(rolling_window).std()
    df['Anomaly'] = abs(df['Pressure_bar'] - rolling_mean) > (anomaly_z * rolling_std)
    df['Anomaly'] = df['Anomaly'].fillna(False)
    return df


def find_worst_cluster(df, cluster_window=100, padding_readings=100):
    """Finds the time period with the densest cluster of flagged anomalies.

    A slow drift often produces several short, separate anomaly flags
    close together in time rather than one continuous flagged block,
    because a rolling baseline partially adapts as pressure drifts.
    Treating nearby flags as one underlying incident is a more realistic
    read on operational impact than picking whichever single reading has
    the largest raw deviation, which tends to surface a brief noise spike.

    Caveat: on noisy synthetic data, ordinary randomness can occasionally
    produce a tighter false-positive cluster than the real degradation
    elsewhere in the series. If the picked incident looks wrong against
    the full dashboard, use select_window_by_date() instead with a range
    chosen by eye from the Composite Health panel.

    Args:
        df: Sensor DataFrame with an 'Anomaly' boolean column (see load_data).
        cluster_window: Rolling window (in readings) used to count how many
            anomalies fall near each point in time.
        padding_readings: Extra readings included before/after the incident
            span, so the resulting plot has context rather than being
            cropped tight to just the flagged points.

    Returns:
        Tuple of (window, incident, flagged): the padded DataFrame slice to
        plot, the full contiguous span covering the cluster (used for
        summary stats), and just the readings that were flagged anomalous
        within it (used as scatter markers).
    """
    density = df['Anomaly'].rolling(cluster_window, center=True, min_periods=1).sum()
    peak_idx = density.idxmax()

    lower = max(0, peak_idx - cluster_window)
    upper = min(len(df) - 1, peak_idx + cluster_window)
    nearby = df.iloc[lower:upper]
    flagged = nearby[nearby['Anomaly']]
    if flagged.empty:
        flagged = df.iloc[[peak_idx]]

    start_idx, end_idx = flagged.index.min(), flagged.index.max()
    incident = df.iloc[start_idx:end_idx + 1]
    window = df.iloc[max(0, start_idx - padding_readings): end_idx + padding_readings]
    return window, incident, flagged


def select_window_by_date(df, start, end, padding_readings=100):
    """Builds a case-study window around a manually chosen date range.

    Automatic cluster-picking (find_worst_cluster) is a convenience
    default, but it can be misled by ordinary noise producing a tighter
    false-positive cluster than the real, slower degradation elsewhere in
    the data. In practice an engineer reviewing the full dashboard
    (particularly the Composite Health panel) would spot the real incident
    by eye and zoom into it directly — pass in the start/end identified
    that way.

    Args:
        df: Sensor DataFrame with an 'Anomaly' boolean column (see load_data).
        start: Start of the incident, e.g. '2026-01-05'.
        end: End of the incident, e.g. '2026-01-06 18:00:00'.
        padding_readings: Extra readings included before/after the chosen
            range for context in the resulting plot.

    Returns:
        Tuple of (window, incident, flagged), matching find_worst_cluster's
        return shape.
    """
    start, end = pd.Timestamp(start), pd.Timestamp(end)
    incident = df[(df['Timestamp'] >= start) & (df['Timestamp'] <= end)]
    flagged = incident[incident['Anomaly']]

    start_idx, end_idx = incident.index.min(), incident.index.max()
    window = df.iloc[max(0, start_idx - padding_readings): end_idx + padding_readings]
    return window, incident, flagged


def hypothesize_root_cause(df, incident):
    """Compares the incident's average readings to the dataset baseline to suggest a cause.

    Same simplified rule-of-thumb used in analyze_data.py's
    generate_rca_report(): pressure down + temperature up looks different
    from pressure down + temperature flat, and each combination points to
    a different plausible failure mode. Uses the full incident window's
    average, not just the sparse flagged readings within it, since a few
    scattered flags can straddle both the dip and the recovery bounce and
    average out to nothing. This is illustrative, not a validated
    diagnostic model.

    Args:
        df: Full sensor DataFrame, used to compute the overall baseline.
        incident: The full contiguous span of readings that make up the
            incident (not just the flagged subset).

    Returns:
        A short text hypothesis for the likely root cause.
    """
    pressure_drop = (df['Pressure_bar'].mean() - incident['Pressure_bar'].mean()) > 3
    temp_rise = (incident['Temperature_C'].mean() - df['Temperature_C'].mean()) > 1
    flow_erratic = incident['Flow_m3h'].std() > (df['Flow_m3h'].std() * 1.5)

    if pressure_drop and temp_rise:
        return "Suspected Impeller Wear / Recirculation"
    elif pressure_drop and not temp_rise:
        return "Suspected Suction Valve Throttling or Leak"
    elif flow_erratic and not pressure_drop:
        return "Suspected Multiphase Flow Meter Error or Slugging"
    else:
        return "Undetermined - Review Manually"


def build_case_study(df, window, incident, flagged, filename='event_case_study.png'):
    """Builds a zoomed, annotated figure around a single detected incident.

    Rather than showing the full 10-day monitoring window (which
    compresses one incident into an unreadable sliver), this zooms into
    the incident plus padding before/after, so pressure, flow and
    temperature behaviour around it is actually legible — the same reason
    a geoscientist zooms into a zone of interest rather than presenting a
    full, congested section.

    Args:
        df: Full sensor DataFrame, used to compute the baseline shown in
            the summary box.
        window: The padded DataFrame slice to plot.
        incident: The full contiguous span of readings that make up the
            incident, used for the shaded region and summary statistics.
        flagged: The subset of incident readings that tripped the anomaly
            detector, shown as scatter markers.
        filename: Output path for the saved case-study image.

    Returns:
        None. Saves and displays the figure.
    """
    event_start, event_end = incident['Timestamp'].min(), incident['Timestamp'].max()
    root_cause = hypothesize_root_cause(df, incident)
    max_deviation = round(incident['Pressure_bar'].min() - df['Pressure_bar'].mean(), 2)

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(11, 8.5), sharex=True)
    fig.subplots_adjust(bottom=0.24)

    ax1.plot(window['Timestamp'], window['Pressure_bar'], color='tab:blue', label='Pressure (bar)')
    ax1.axvspan(event_start, event_end, color='orange', alpha=0.25, label='Detected Incident')
    ax1.scatter(flagged['Timestamp'], flagged['Pressure_bar'], color='red', s=25, label='Flagged Reading', zorder=5)
    ax1.set_ylabel('Pressure (bar)')
    ax1.set_title(f"Case Study: Incident around {event_start}")
    ax1.legend(loc='upper right')
    ax1.grid(True, alpha=0.3)

    ax2b = ax2.twinx()
    l1, = ax2.plot(window['Timestamp'], window['Flow_m3h'], color='tab:green', label='Flow (m3/h)')
    l2, = ax2b.plot(window['Timestamp'], window['Temperature_C'], color='tab:red', label='Temperature (C)')
    ax2.axvspan(event_start, event_end, color='orange', alpha=0.25)
    ax2.set_ylabel('Flow (m\u00b3/h)', color='tab:green')
    ax2b.set_ylabel('Temperature (\u00b0C)', color='tab:red')
    ax2.set_xlabel('Timestamp')
    ax2.grid(True, alpha=0.3)
    ax2.legend(handles=[l1, l2], loc='upper right')

    action = RECOMMENDED_ACTIONS.get(root_cause, "Manual review recommended.")
    summary = (
        f"Incident duration: {len(incident)} readings   |   Max deviation: {max_deviation} bar\n"
        f"Root cause hypothesis: {root_cause}\n"
        f"Recommended action: {action}"
    )
    fig.text(0.5, 0.06, summary, fontsize=10, va='center', ha='center',
              bbox=dict(boxstyle='round', facecolor='#f2f2f2', edgecolor='grey'))

    plt.savefig(filename, dpi=150)
    plt.show()


